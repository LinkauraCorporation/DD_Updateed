/**
 * Main AI Copilot generation entrypoint.
 *
 * Enforces:
 * 1. Tenant Isolation: Every query requires organizationId.
 * 2. RBAC: User role strictly dictates context visibility.
 * 3. Deterministic Safety: Arithmetic and financial computations are never generated by LLM tokens.
 * 4. Offline / Local Fallback: If Gemini endpoint is unavailable, deterministic local engines respond.
 */
export async function generateCopilotResponse(
  organizationId: string,
  userRole: AIUserRole,
  request: AIRequest,
  timezoneContext: { operationalTimezone?: string; dispatcherTimezone?: string } = {}
): Promise<AIResponse> {
  if (!organizationId) {
    throw new Error('Tenant organization ID is required for AI Copilot execution.');
  }

  const opsTimezone = timezoneContext.operationalTimezone || DEFAULT_OPERATIONAL_TIMEZONE;
  const dispTimezone = timezoneContext.dispatcherTimezone || DEFAULT_DISPATCHER_TIMEZONE;

  // 1. Build compact, role-filtered context
  const context = await buildCopilotContext({
    organizationId,
    userRole,
    operationalTimezone: opsTimezone,
    dispatcherTimezone: dispTimezone,
    specificLoadId: request.loadId,
    specificClaimId: request.claimId,
  });

  const requestedMode = request.mode || 'local';

  // 2. If Gemini mode requested, attempt server-side proxy
  if (requestedMode === 'gemini') {
    try {
      const serverResponse = await callServerGeminiEndpoint(context, request);
      if (serverResponse) {
        return serverResponse;
      }
    } catch (e) {
      console.warn('Server-side Gemini endpoint unavailable. Falling back gracefully to Local Mode.', e);
    }
  }

  // 3. Deterministic Local Template Execution (Safe, Offline-Ready, Fast)
  return executeLocalDeterministicEngine(organizationId, context, request);
}

/**
 * Attempts to contact server-side Gemini gateway if configured.
 * Note: Browser client never holds or transmits the raw GEMINI_API_KEY.
 */
async function callServerGeminiEndpoint(
  context: AIContext,
  request: AIRequest
): Promise<AIResponse | null> {
  try {
    const orgId =
      context.organizationId ||
      (() => {
        try {
          return localStorage.getItem('dispatchdesk_active_org_id') || 'demo-org-1';
        } catch {
          return 'demo-org-1';
        }
      })();

    let token = 'demo-token';
    try {
      const { data } = await supabase.auth.getSession();
      if (data?.session?.access_token) {
        token = data.session.access_token;
      }
    } catch {
      // ignore session lookup failure, use fallback token
    }

    const res = await fetch('/api/ai/generate', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`,
        'x-organization-id': orgId,
      },
      body: JSON.stringify({
        context: { ...context, organizationId: orgId },
        request,
        organizationId: orgId,
      }),
    });

    if (!res.ok) {
      return null;
    }

    const data = await res.json();
    return data as AIResponse;
  } catch {
    return null;
  }
}

/**
 * Deterministic Domain Template Engine
 * Generates grounded, industry-standard dispatch briefings and communications.
 */
async function executeLocalDeterministicEngine(
  organizationId: string,
  context: AIContext,
  request: AIRequest
): Promise<AIResponse> {
  const timestamp = new Date().toISOString();
  const responseId = `ai-resp-${Date.now()}-${Math.random().toString(36).substr(2, 6)}`;

  switch (request.action) {
    case 'shift_handover_digest':
      return generateLocalShiftHandoverDigest(responseId, timestamp, context);

    case 'risk_analysis':
      return generateLocalRiskAnalysis(responseId, timestamp, context);

    case 'analyze_load':
      return generateLocalLoadAnalysis(responseId, timestamp, context, request);

    case 'explain_load_risk':
      return generateLocalExplainLoadRisk(responseId, timestamp, context, request);

    case 'summarize_load':
      return generateLocalSummarizeLoad(responseId, timestamp, context, request);

    case 'detention_escalation':
      return generateLocalDetentionEscalation(organizationId, responseId, timestamp, context, request);

    case 'driver_instructions':
      return generateLocalDriverInstructions(responseId, timestamp, context, request);

    case 'missing_paperwork':
      return generateLocalMissingPaperworkDigest(responseId, timestamp, context);

    case 'extract_tasks_from_notes':
      return generateLocalExtractTasksFromNotes(responseId, timestamp, context, request);

    case 'broker_email':
      return generateLocalBrokerEmail(responseId, timestamp, context, request);

    case 'general_query':
    default:
      return generateLocalGeneralQueryResponse(responseId, timestamp, context, request);
  }
}

/**
 * 1. Local Shift Handover Digest
 */
function generateLocalShiftHandoverDigest(
  responseId: string,
  timestamp: string,
  ctx: AIContext
): AIResponse {
  const activeLoadsCount = ctx.loads.filter((l: AIContextLoad) => ['booked', 'in_transit'].includes(l.pipelineStatus)).length;
  const activeDetentions = ctx.pendingAccessorials.filter((a: AIContextAccessorial) => a.isActiveDetention);
  const criticalCheckCalls = ctx.recentCheckCalls.filter((c: AIContextCheckCall) => c.isException);
  const missingDocs = ctx.missingDocuments.filter((d: AIContextDocument) => d.isMissingCritical);

  const groundingSources: GroundingSource[] = [];
  ctx.loads.slice(0, 5).forEach((l: AIContextLoad) => {
    groundingSources.push({
      type: 'load',
      id: l.id,
      label: `Load ${l.loadNumber} (${l.origin} ➔ ${l.destination})`,
    });
  });

  let markdown = `### 📋 Cross-Timezone Dispatch Handover Briefing\n`;
  markdown += `**Operational Time (Ops):** ${ctx.currentTimeOps} (${ctx.operationalTimezone})  \n`;
  markdown += `**Dispatcher Local Time:** ${ctx.currentTimeDispatcher} (${ctx.dispatcherTimezone})  \n\n`;

  markdown += `---\n\n`;

  // Summary Metrics Strip
  markdown += `#### 📊 Fleet Status Overview\n`;
  markdown += `* **Active Dispatches:** ${activeLoadsCount} active loads in pipeline\n`;
  markdown += `* **Operational Exceptions:** ${criticalCheckCalls.length} check call exception(s) logged\n`;
  markdown += `* **Active Detention Clocks:** ${activeDetentions.length} truck(s) currently waiting past free time\n`;
  markdown += `* **Missing Critical Docs:** ${missingDocs.length} load(s) requiring immediate paperwork\n\n`;

  // Priority Attention Section
  markdown += `#### 🚨 High Priority Watchlist\n`;
  if (ctx.operationalAlerts.length > 0) {
    ctx.operationalAlerts.forEach((alert: string) => {
      markdown += `* ⚠️ ${alert}\n`;
    });
  } else {
    markdown += `* ✅ No critical dispatch exceptions or delayed trucks currently detected.\n`;
  }
  markdown += `\n`;

  // Active Loads Breakdown
  markdown += `#### 🚚 Active Loads in Transit / Booked\n`;
  if (ctx.loads.length === 0) {
    markdown += `*No active loads found for this organization.*\n`;
  } else {
    ctx.loads.forEach((l: AIContextLoad) => {
      const statusBadge = l.pipelineStatus.replace('_', ' ').toUpperCase();
      markdown += `* **${l.loadNumber}** [${statusBadge}] — **${l.carrierClientName}** (Truck #${l.truckNumber} / ${l.driverName})\n`;
      markdown += `  * **Route:** ${l.origin} ➔ ${l.destination}\n`;
      markdown += `  * **Delivery Window:** ${l.deliveryTimeFormatted}\n`;
      if (l.rateFormatted) {
        markdown += `  * **Gross Rate:** ${l.rateFormatted}${l.rpmFormatted ? ` (${l.rpmFormatted})` : ''}\n`;
      }
      if (l.isAtRisk) {
        markdown += `  * ⚠️ *Flagged as At Risk in tracking*\n`;
      }
    });
  }

  markdown += `\n#### 📝 Recommended Next Actions for Incoming Shift\n`;
  const recommendations: string[] = [];
  if (activeDetentions.length > 0) {
    recommendations.push(`Send updated detention claim emails for ${activeDetentions.map((a: AIContextAccessorial) => a.loadNumber).join(', ')} with revised rate con requests.`);
  }
  if (missingDocs.length > 0) {
    recommendations.push(`Contact drivers on delivered loads to obtain signed POD photos for factoring submission.`);
  }
  recommendations.push(`Perform standard 4-hour check call cycle for all in-transit freight.`);

  recommendations.forEach((rec: string, idx: number) => {
    markdown += `${idx + 1}. ${rec}\n`;
  });

  return {
    id: responseId,
    action: 'shift_handover_digest',
    mode: 'local',
    title: 'Cross-Timezone Shift Handover Briefing',
    content: markdown,
    markdownContent: markdown,
    timestamp,
    groundingSources,
    recommendations,
    suggestedActions: [
      { label: 'Copy Handover to Clipboard', action: 'copy_clipboard', payload: { text: markdown } },
      { label: 'View Tracking Radar', action: 'navigate_tracking' },
    ],
    isDraft: false,
    requiresConfirmation: false,
  };
}

/**
 * 2. Local Risk & Delay Analysis
 */
function generateLocalRiskAnalysis(
  responseId: string,
  timestamp: string,
  ctx: AIContext
): AIResponse {
  const exceptions = ctx.recentCheckCalls.filter((c: AIContextCheckCall) => c.isException);
  const activeDetentions = ctx.pendingAccessorials.filter((a: AIContextAccessorial) => a.isActiveDetention);

  const groundingSources: GroundingSource[] = [];
  exceptions.forEach((e: AIContextCheckCall) => {
    groundingSources.push({
      type: 'check_call',
      id: e.id,
      label: `Check Call on Load ${e.loadNumber} (${e.status})`,
    });
  });

  let markdown = `### ⚠️ Operational Risk & Delay Analysis\n\n`;
  markdown += `Analyzed ${ctx.loads.length} loads and ${ctx.recentCheckCalls.length} recent check calls.\n\n`;

  if (exceptions.length === 0 && activeDetentions.length === 0 && ctx.operationalAlerts.length === 0) {
    markdown += `✅ **All active operations running on schedule.** No delay exceptions, breakdown logs, or detention overruns currently flagged.\n`;
  } else {
    markdown += `#### 🚨 Identified Risk Factors\n\n`;

    if (exceptions.length > 0) {
      markdown += `**1. Check Call Exceptions & Delays:**\n`;
      exceptions.forEach((exc: AIContextCheckCall) => {
        markdown += `* **Load ${exc.loadNumber}:** Status \`${exc.status.toUpperCase()}\` (${exc.callType})\n`;
        markdown += `  * Location: ${exc.location}\n`;
        markdown += `  * Notes: ${exc.notes || 'No notes provided'}\n`;
        markdown += `  * Logged: ${exc.loggedAtFormatted}\n`;
      });
      markdown += `\n`;
    }

    if (activeDetentions.length > 0) {
      markdown += `**2. Facility Detention Bottlenecks:**\n`;
      activeDetentions.forEach((det: AIContextAccessorial) => {
        markdown += `* **Load ${det.loadNumber}:** Driver waiting at ${det.facilityName || 'Dock'} (${det.billableHours ?? 0} billable hrs accrued at ${det.hourlyRateFormatted || '$75/hr'}).\n`;
      });
      markdown += `\n`;
    }

    if (ctx.operationalAlerts.length > 0) {
      markdown += `**3. Stale Check-In Alerts:**\n`;
      ctx.operationalAlerts.forEach((alert: string) => {
        markdown += `* ${alert}\n`;
      });
      markdown += `\n`;
    }
  }

  const recommendations = [
    'Directly call drivers flagged with overdue check-ins to verify highway location and updated ETA.',
    'Notify broker dispatchers via email proactively for any delayed pickup/delivery to avoid broker TONU or late fines.',
  ];

  return {
    id: responseId,
    action: 'risk_analysis',
    mode: 'local',
    title: 'Operational Risk & Delay Analysis',
    content: markdown,
    markdownContent: markdown,
    timestamp,
    groundingSources,
    recommendations,
    suggestedActions: [
      { label: 'View Active Exceptions', action: 'filter_exceptions' },
    ],
    isDraft: false,
    requiresConfirmation: false,
  };
}

/**
 * 3. Local Detention Escalation Email Draft
 */
async function generateLocalDetentionEscalation(
  organizationId: string,
  responseId: string,
  timestamp: string,
  ctx: AIContext,
  request: AIRequest
): Promise<AIResponse> {
  const accessorials = await accessorialService.getAccessorials(organizationId);

  // Find target claim by specific claimId, or by loadId, or first active detention
  let targetClaim: AccessorialWithLoad | undefined;
  if (request.claimId) {
    targetClaim = accessorials.find((a: AccessorialWithLoad) => a.id === request.claimId);
  } else if (request.loadId) {
    targetClaim = accessorials.find(
      (a: AccessorialWithLoad) => a.load_id === request.loadId && a.type === 'detention'
    ) || accessorials.find((a: AccessorialWithLoad) => a.load_id === request.loadId);
  }

  if (!targetClaim) {
    targetClaim = accessorials.find((a: AccessorialWithLoad) => a.type === 'detention') || accessorials[0];
  }

  if (!targetClaim) {
    const markdown = `⚠️ **No accessorial or detention claim found** for the selected context.\n\nPlease select or create a detention claim in the Accessorials module first.`;
    return {
      id: responseId,
      action: 'detention_escalation',
      mode: 'local',
      title: 'Detention Notice (No Claim Found)',
      content: markdown,
      markdownContent: markdown,
      timestamp,
      groundingSources: [],
      recommendations: ['Create a detention claim in the Accessorials tab.'],
      suggestedActions: [],
      isDraft: true,
      requiresConfirmation: true,
    };
  }

  const det = targetClaim.detention_details;
  const detCalc = calculateDetention({
    arrivalTime: det?.arrival_time || new Date().toISOString(),
    departureTime: det?.departure_time,
    freeTimeHours: det?.free_time_hours ?? 2.0,
    hourlyRate: det?.hourly_rate ?? 75.0,
  });

  const emailDraft = generateBrokerDetentionEmail(targetClaim, detCalc, {
    operationalTimezone: ctx.operationalTimezone,
    dispatcherTimezone: ctx.dispatcherTimezone,
    companyName: targetClaim.load?.client?.company_name || 'Carrier Fleet Operations',
  });

  const markdown = `### ✉️ Draft Broker Detention Escalation Email\n\n` +
    `**Subject:** \`${emailDraft.subject}\`\n\n` +
    `\`\`\`text\n${emailDraft.body}\n\`\`\`\n\n` +
    `*Note: This is an unsubmitted draft. Review the details and copy into your email client.*`;

  return {
    id: responseId,
    action: 'detention_escalation',
    mode: 'local',
    title: `Broker Detention Claim Draft (Load #${targetClaim.load?.load_number || 'N/A'})`,
    content: emailDraft.body,
    markdownContent: markdown,
    subject: emailDraft.subject,
    timestamp,
    groundingSources: [
      {
        type: 'accessorial',
        id: targetClaim.id,
        label: `Claim ${targetClaim.id} ($${targetClaim.amount.toFixed(2)})`,
      },
    ],
    recommendations: [
      'Ensure the driver obtains a stamped check-in / check-out time on the paper BOL before leaving the facility.',
      'Attach the detention calculation breakdown and request a revised Rate Confirmation.',
    ],
    suggestedActions: [
      { label: 'Copy Email Body', action: 'copy_clipboard', payload: { text: emailDraft.body } },
      { label: 'Copy Subject', action: 'copy_clipboard', payload: { text: emailDraft.subject } },
    ],
    isDraft: true,
    requiresConfirmation: true,
  };
}

