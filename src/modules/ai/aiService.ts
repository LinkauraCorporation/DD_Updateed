/**
 * 5. Local Missing Paperwork & POD Audit
 */
function generateLocalMissingPaperworkDigest(
  responseId: string,
  timestamp: string,
  ctx: AIContext
): AIResponse {
  const missing = ctx.missingDocuments;
  const critical = missing.filter((m: AIContextDocument) => m.isMissingCritical);

  let markdown = `### 📑 Freight Paperwork & Document Audit\n\n`;

  if (missing.length === 0) {
    markdown += `✅ **All required freight documents are accounted for.** No missing Rate Cons, BOLs, or PODs detected across active loads.\n`;
  } else {
    markdown += `Found **${missing.length} missing document item(s)** across active dispatches (${critical.length} critical for invoicing):\n\n`;

    missing.forEach((item: AIContextDocument) => {
      const docLabel = item.docType.replace('_', ' ').toUpperCase();
      const badge = item.isMissingCritical ? '🔴 CRITICAL' : '🟡 PENDING';
      markdown += `* **Load ${item.loadNumber}:** Missing \`${docLabel}\` [${badge}]\n`;
    });

    markdown += `\n#### 💡 Action Recommendations\n`;
    markdown += `1. **Rate Confirmations:** Contact broker rep to request signed EDI rate con.\n`;
    markdown += `2. **Proof of Delivery (POD):** Request high-resolution photo from driver immediately upon dock completion.\n`;
  }

  return {
    id: responseId,
    action: 'missing_paperwork',
    mode: 'local',
    title: 'Missing Freight Paperwork Audit',
    content: markdown,
    markdownContent: markdown,
    timestamp,
    groundingSources: missing.map((m: AIContextDocument) => ({
      type: 'document' as const,
      id: `${m.loadNumber}-${m.docType}`,
      label: `Load ${m.loadNumber} (Missing ${m.docType})`,
    })),
    recommendations: [
      'Invoices cannot be factored without a verified signed POD and Rate Confirmation.',
    ],
    suggestedActions: [
      { label: 'Open Documents Hub', action: 'navigate_documents' },
    ],
    isDraft: false,
    requiresConfirmation: false,
  };
}

