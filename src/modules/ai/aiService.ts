/**
 * 11. Extract Follow-up Tasks from Notes & Operations
 * Evaluates recent activities, check calls, detentions, and paperwork to suggest actionable tasks.
 * NOTE: AI only suggests tasks. Actual creation requires human confirmation.
 */
function generateLocalExtractTasksFromNotes(
  responseId: string,
  timestamp: string,
  ctx: AIContext,
  request: AIRequest
): AIResponse {
  const suggestedTasks: Array<{
    title: string;
    category: string;
    priority: 'urgent' | 'high' | 'normal' | 'low';
    dueOffsetHours: number;
    description: string;
    loadId?: string;
    loadNumber?: string;
    reason: string;
  }> = [];

  const groundingSources: GroundingSource[] = [];

  // A. Check for exceptions in check calls
  ctx.recentCheckCalls.forEach((call) => {
    if (call.isException) {
      const targetLoad = ctx.loads.find((l) => l.loadNumber === call.loadNumber);
      suggestedTasks.push({
        title: `Follow up on check-call exception for Load #${call.loadNumber}`,
        category: 'check_call_follow_up',
        priority: call.callType === 'breakdown' ? 'urgent' : 'high',
        dueOffsetHours: 1,
        description: `Check-call exception logged: ${call.notes || call.status}. Verify vehicle status and notify broker if delivery ETA is impacted.`,
        loadId: targetLoad?.id,
        loadNumber: call.loadNumber,
        reason: `Recent check-call flagged as ${call.status} (${call.callType})`,
      });
      groundingSources.push({
        type: 'check_call',
        id: call.id,
        label: `Exception on Load #${call.loadNumber}`,
      });
    }
  });

  // B. Check for active detentions needing claim follow-up
  ctx.pendingAccessorials.forEach((acc) => {
    if (acc.isActiveDetention) {
      const targetLoad = ctx.loads.find((l) => l.loadNumber === acc.loadNumber);
      suggestedTasks.push({
        title: `Follow up on broker detention claim for Load #${acc.loadNumber}`,
        category: 'detention_reminder',
        priority: 'high',
        dueOffsetHours: 2,
        description: `Driver has accrued ${acc.billableHours ?? 0} hrs billable detention at ${acc.facilityName || 'dock'}. Request updated rate confirmation from broker.`,
        loadId: targetLoad?.id,
        loadNumber: acc.loadNumber,
        reason: `Active detention clock running past free time`,
      });
      groundingSources.push({
        type: 'accessorial',
        id: acc.id,
        label: `Active Detention on Load #${acc.loadNumber}`,
      });
    }
  });

  // C. Check for missing PODs on delivered loads
  ctx.missingDocuments.forEach((doc) => {
    if (doc.isMissingCritical && doc.docType === 'pod') {
      const targetLoad = ctx.loads.find((l) => l.loadNumber === doc.loadNumber);
      suggestedTasks.push({
        title: `Collect signed POD from driver for Load #${doc.loadNumber}`,
        category: 'pod_collection',
        priority: 'high',
        dueOffsetHours: 4,
        description: `Load #${doc.loadNumber} is delivered but missing signed Proof of Delivery. Contact driver to obtain document photo for billing.`,
        loadId: targetLoad?.id,
        loadNumber: doc.loadNumber,
        reason: `Delivered load missing POD required for invoice submission`,
      });
      groundingSources.push({
        type: 'document',
        id: `${doc.loadId}-pod`,
        label: `Missing POD: Load #${doc.loadNumber}`,
      });
    }
  });

  // D. Scan recent dispatcher notes for action items (e.g., "call broker", "reschedule", "verify")
  ctx.recentActivities.forEach((act) => {
    if (act.type === 'dispatcher_note' || act.type === 'broker_update') {
      const text = `${act.title} ${act.description}`.toLowerCase();
      const targetLoad = act.loadNumber ? ctx.loads.find((l) => l.loadNumber === act.loadNumber) : undefined;

      if (text.includes('call') || text.includes('contact') || text.includes('follow up') || text.includes('remind')) {
        suggestedTasks.push({
          title: `Dispatcher follow-up: ${act.title.slice(0, 50)}`,
          category: 'general_operational',
          priority: act.isCriticalAlert ? 'urgent' : 'normal',
          dueOffsetHours: 3,
          description: `Note excerpt: "${act.description}". Ensure item is addressed during shift.`,
          loadId: targetLoad?.id,
          loadNumber: act.loadNumber,
          reason: `Action keyword detected in dispatcher note by ${act.actorName}`,
        });
      }
    }
  });

  // Deduplicate suggested tasks by title/load
  const uniqueTasks = suggestedTasks.filter(
    (t, index, self) =>
      index === self.findIndex((other) => other.title === t.title && other.loadNumber === t.loadNumber)
  );

  let markdown = `### 📋 Extracted Dispatch Follow-up Tasks\n\n`;
  markdown += `Scanned dispatcher notes, active detention clocks, check-call logs, and document audits.\n`;
  markdown += `**Found ${uniqueTasks.length} suggested actionable follow-up task(s).**\n\n`;
  markdown += `*Note: In accordance with human-in-the-loop safety, tasks are suggested for your review. Click "Create Task" on any item to confirm and add to your task board.*\n\n`;
  markdown += `---\n\n`;

  if (uniqueTasks.length === 0) {
    markdown += `✅ **No pending follow-up tasks detected.** All check calls are normal, no active detentions are unbilled, and all delivered loads have completed paperwork.\n`;
  } else {
    uniqueTasks.forEach((st, idx) => {
      const loadRef = st.loadNumber ? ` (Load #${st.loadNumber})` : '';
      markdown += `#### ${idx + 1}. [${st.priority.toUpperCase()}] ${st.title}\n`;
      markdown += `* **Category:** \`${st.category}\`${loadRef}\n`;
      markdown += `* **Suggested Due:** In ${st.dueOffsetHours} hour(s)\n`;
      markdown += `* **Reason:** ${st.reason}\n`;
      markdown += `* **Details:** ${st.description}\n\n`;
    });
  }

  // Construct interactive suggestedActions
  const suggestedActions = uniqueTasks.map((t) => {
    const dueAt = new Date(Date.now() + t.dueOffsetHours * 3600000).toISOString();
    return {
      label: `Create: ${t.title.slice(0, 35)}...`,
      action: 'create_task',
      payload: {
        title: t.title,
        category: t.category,
        priority: t.priority,
        due_at: dueAt,
        description: t.description,
        load_id: t.loadId,
        load_number: t.loadNumber,
      },
    };
  });

  return {
    id: responseId,
    action: 'extract_tasks_from_notes',
    mode: 'local',
    title: `Extracted Follow-up Tasks (${uniqueTasks.length} Suggested)`,
    content: markdown,
    markdownContent: markdown,
    timestamp,
    groundingSources,
    recommendations: [
      'Review each suggested task and customize due dates or assignees before confirming.',
      'Completed tasks automatically feed into the next shift handover digest.',
    ],
    suggestedActions,
    isDraft: true,
    requiresConfirmation: true,
  };
}

/**
 * Non-blocking activity audit logging for AI Copilot operations.
 */
export async function logAIOperationActivity(
  organizationId: string,
  params: {
    actorId?: string;
    actorName?: string;
    loadId?: string;
    action: string;
    mode: string;
    title: string;
    isDraft?: boolean;
  }
): Promise<void> {
  if (!organizationId) return;

  const targetLoadId = params.loadId || 'global-dispatch';
  const actorName = params.actorName || 'Dispatcher';
  const actorId = params.actorId || 'usr-dispatcher';

  try {
    await activityService.logActivity(organizationId, {
      loadId: targetLoadId,
      type: 'ai_assistant',
      title: `AI Copilot: ${params.title}`,
      description: `Generated ${params.title} using ${params.mode.toUpperCase()} engine. ${params.isDraft ? '(AI Draft — Human Review Required)' : '(Informational Context)'}`,
      actorId,
      actorName,
      metadata: {
        action: params.action,
        mode: params.mode,
        isDraft: Boolean(params.isDraft),
        humanReviewRequired: Boolean(params.isDraft),
        targetLoadId: params.loadId,
      },
    });
  } catch (err) {
    // Non-blocking failure: never throw or fail UI on audit log errors
    console.warn('Non-blocking AI activity logging notice:', err);
  }
}

