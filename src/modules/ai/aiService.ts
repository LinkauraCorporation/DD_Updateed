/**
 * 9. Local Single Load Risk Explanation
 */
function generateLocalExplainLoadRisk(
  responseId: string,
  timestamp: string,
  ctx: AIContext,
  request: AIRequest
): AIResponse {
  const targetLoad = request.loadId
    ? ctx.loads.find((l: AIContextLoad) => l.id === request.loadId)
    : ctx.loads[0];

  if (!targetLoad) {
    const markdown = `⚠️ **No load found to analyze risk.**`;
    return {
      id: responseId,
      action: 'explain_load_risk',
      mode: 'local',
      title: 'Risk Explanation (Not Found)',
      content: markdown,
      markdownContent: markdown,
      timestamp,
      groundingSources: [],
      recommendations: [],
      suggestedActions: [],
      isDraft: false,
      requiresConfirmation: false,
    };
  }

  const loadCalls = ctx.recentCheckCalls.filter((c: AIContextCheckCall) => c.loadNumber === targetLoad.loadNumber);
  const loadAccessorials = ctx.pendingAccessorials.filter((a: AIContextAccessorial) => a.loadNumber === targetLoad.loadNumber);
  const loadDocs = ctx.missingDocuments.filter((d: AIContextDocument) => d.loadNumber === targetLoad.loadNumber);

  const exceptions = loadCalls.filter((c) => c.isException);
  const activeDetention = loadAccessorials.find((a) => a.isActiveDetention);
  const criticalDocs = loadDocs.filter((d) => d.isMissingCritical);
  const isMissingRecentCheckIn = Boolean(
    targetLoad.isMissingRecentCheckIn ??
      (targetLoad.pipelineStatus === 'in_transit' && loadCalls.length === 0)
  );

  let riskLevel: 'LOW' | 'MODERATE' | 'HIGH' | 'CRITICAL' = 'LOW';
  if (exceptions.length > 0 || activeDetention) {
    riskLevel = 'HIGH';
  } else if (criticalDocs.length > 0 || isMissingRecentCheckIn) {
    riskLevel = 'MODERATE';
  }

  let markdown = `### ⚠️ Risk Assessment: Load #${targetLoad.loadNumber}\n\n`;
  markdown += `**Overall Risk Evaluation:** \`${riskLevel} RISK\`  \n`;
  markdown += `**Driver:** ${targetLoad.driverName} (Truck #${targetLoad.truckNumber}) | **Route:** ${targetLoad.origin} ➔ ${targetLoad.destination}  \n\n`;

  markdown += `---\n\n`;

  markdown += `#### 🚨 Risk Factors Identified\n`;
  let hasFactors = false;

  if (exceptions.length > 0) {
    hasFactors = true;
    markdown += `* **Transit Exceptions:**\n`;
    exceptions.forEach((e) => {
      markdown += `  * 🔴 Status: \`${e.status.toUpperCase()}\` (${e.callType}) at ${e.location}. Notes: "${e.notes || 'N/A'}"\n`;
    });
  }

  if (activeDetention) {
    hasFactors = true;
    markdown += `* **Active Facility Detention Clock:**\n`;
    markdown += `  * 🔴 Driver is currently waiting past free time (${activeDetention.billableHours ?? 0} hrs accrued at ${activeDetention.facilityName || 'dock'}).\n`;
  }

  if (criticalDocs.length > 0) {
    hasFactors = true;
    markdown += `* **Paperwork Vulnerabilities:**\n`;
    criticalDocs.forEach((d) => {
      markdown += `  * 🟡 Missing critical \`${d.docType.replace('_', ' ').toUpperCase()}\` for invoicing.\n`;
    });
  }

  if (isMissingRecentCheckIn) {
    hasFactors = true;
    if (loadCalls.length === 0) {
      const scopeDesc =
        targetLoad.pipelineStatus === 'booked'
          ? 'booked freight past scheduled pickup'
          : 'active transit freight';
      markdown += `* **Missing Dispatch Check-In:** No check calls logged for ${scopeDesc}.\n`;
    } else {
      const timeAgo = targetLoad.timeSinceLastUpdate || 'over 24 hours ago';
      markdown += `* **Stale Tracking:** Overdue check call — last status update was ${timeAgo}.\n`;
    }
  }

  if (!hasFactors) {
    markdown += `* ✅ **No active risk factors detected.** Dispatch timeline, appointments, and check-in logs are normal.\n`;
  }

  markdown += `\n#### 🛡️ Mitigation Playbook\n`;
  const recommendations: string[] = [];
  if (exceptions.length > 0) {
    recommendations.push('Contact receiver facility immediately to advise of delay and secure an updated delivery appointment window.');
    recommendations.push('Send proactive transit update email to broker representative.');
  }
  if (activeDetention) {
    recommendations.push('Alert broker in writing regarding ongoing detention and prepare revised rate confirmation.');
  }
  if (criticalDocs.length > 0) {
    recommendations.push('Message driver on WhatsApp requesting signed document photo prior to departure.');
  }
  if (isMissingRecentCheckIn) {
    recommendations.push(
      `Contact driver ${targetLoad.driverName} (${targetLoad.driverPhone || 'Truck #' + targetLoad.truckNumber}) immediately for urgent GPS location and transit status update.`
    );
  }
  if (recommendations.length === 0) {
    recommendations.push('Perform standard 4-hour check call routine.');
  }

  recommendations.forEach((r, i) => {
    markdown += `${i + 1}. ${r}\n`;
  });

  return {
    id: responseId,
    action: 'explain_load_risk',
    mode: 'local',
    title: `Load #${targetLoad.loadNumber} Risk Assessment (${riskLevel})`,
    content: markdown,
    markdownContent: markdown,
    timestamp,
    groundingSources: [
      { type: 'load', id: targetLoad.id, label: `Load #${targetLoad.loadNumber}` },
      ...exceptions.map((e) => ({ type: 'check_call' as const, id: e.id, label: `Exception (${e.status})` })),
    ],
    recommendations,
    suggestedActions: [
      { label: 'Draft Broker Delay Email', action: 'quick_prompt', payload: { action: 'broker_email', loadId: targetLoad.id } },
      { label: 'Log Check Call Update', action: 'log_check_call', payload: { loadId: targetLoad.id } },
    ],
    isDraft: false,
    requiresConfirmation: false,
  };
}

